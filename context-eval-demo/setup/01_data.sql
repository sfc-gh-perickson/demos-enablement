FROM TABLE(GENERATOR(ROWCOUNT => 40));

-- Opportunities. BOOKING_TYPE drives the bookings trap:
--   Sales bookings  = SUM(AMOUNT_TCV) on all Closed Won deals (incl. renewals, multi-year TCV)
--   Finance bookings = SUM(NET_NEW_ACV) on Closed Won New + Expansion deals only
-- LEAD_SOURCE is stale CRM data; PARTNER_REFERRALS is the system of record for partner sourcing.
CREATE OR REPLACE TABLE OPPORTUNITIES AS
WITH g AS (
  SELECT SEQ4() AS n,
         UNIFORM(13, 400, RANDOM(11)) AS account_id,
         UNIFORM(1, 40, RANDOM(12))   AS rep_id,
         DATEADD(day, UNIFORM(0, 685, RANDOM(13)), '2025-01-01'::DATE) AS close_date,
         UNIFORM(1, 100, RANDOM(14))  AS r_type,
         UNIFORM(1, 100, RANDOM(15))  AS r_stage,
         UNIFORM(10, 250, RANDOM(16)) * 1000 AS acv,
         UNIFORM(1, 3, RANDOM(17))    AS term_years,
         UNIFORM(1, 100, RANDOM(18))  AS r_src
  FROM TABLE(GENERATOR(ROWCOUNT => 3000))
)
SELECT n + 1 AS OPPORTUNITY_ID, account_id AS ACCOUNT_ID, rep_id AS REP_ID,
       CASE WHEN r_type <= 45 THEN 'New' WHEN r_type <= 70 THEN 'Expansion' ELSE 'Renewal' END AS BOOKING_TYPE,
       CASE WHEN close_date > '2026-11-17' THEN (CASE WHEN r_stage <= 50 THEN 'Proposal' ELSE 'Negotiation' END)
            WHEN r_stage <= 60 THEN 'Closed Won' WHEN r_stage <= 85 THEN 'Closed Lost'
            ELSE 'Negotiation' END AS STAGE,
       acv AS ACV,
       acv * term_years AS AMOUNT_TCV,
       CASE WHEN r_type <= 70 THEN acv ELSE 0 END AS NET_NEW_ACV,
       term_years AS TERM_YEARS,
       DATEADD(day, -UNIFORM(30, 180, RANDOM(19)), close_date) AS CREATED_DATE,
       close_date AS CLOSE_DATE,
       CASE WHEN r_src <= 12 THEN 'Partner' WHEN r_src <= 55 THEN 'Inbound' ELSE 'Outbound' END AS LEAD_SOURCE
FROM g;

