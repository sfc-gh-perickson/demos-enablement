-- 400 accounts; 12 test accounts (IS_TEST_ACCOUNT) all in LATAM.
CREATE OR REPLACE TABLE ACCOUNTS AS
SELECT SEQ4()+1 AS ACCOUNT_ID,
       CASE WHEN SEQ4() < 12 THEN 'TEST - Sandbox ' || (SEQ4()+1) ELSE 'Account ' || LPAD(SEQ4()+1, 4, '0') END AS ACCOUNT_NAME,
       CASE WHEN SEQ4() < 12 THEN 4 ELSE MOD(SEQ4(), 4) + 1 END AS REGION_ID,
       CASE MOD(SEQ4(), 3) WHEN 0 THEN 'Enterprise' WHEN 1 THEN 'Mid-Market' ELSE 'SMB' END AS SEGMENT,
       SEQ4() < 12 AS IS_TEST_ACCOUNT
FROM TABLE(GENERATOR(ROWCOUNT => 400));

CREATE OR REPLACE TABLE REPS AS
