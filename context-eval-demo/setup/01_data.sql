-- Partner referrals: system of record. Overlaps LEAD_SOURCE='Partner' only partially.
CREATE OR REPLACE TABLE PARTNER_REFERRALS AS
SELECT ROW_NUMBER() OVER (ORDER BY o.OPPORTUNITY_ID) AS REFERRAL_ID, o.OPPORTUNITY_ID,
       CASE MOD(o.OPPORTUNITY_ID, 5) WHEN 0 THEN 'Northwind Consulting' WHEN 1 THEN 'Contoso Partners'
            WHEN 2 THEN 'Fabrikam SI' WHEN 3 THEN 'Tailspin Advisory' ELSE 'Litware Group' END AS PARTNER_NAME,
       DATEADD(day, -20, o.CREATED_DATE) AS REFERRAL_DATE,
       CASE WHEN MOD(o.OPPORTUNITY_ID, 9) = 0 THEN 'Rejected' ELSE 'Accepted' END AS REFERRAL_STATUS
FROM OPPORTUNITIES o
WHERE MOD(o.OPPORTUNITY_ID, 7) IN (0, 3) AND o.OPPORTUNITY_ID < 90000;
COMMENT ON TABLE PARTNER_REFERRALS IS 'Partner program referrals';

-- Subscriptions: ARR trap. ARR = 12 x MRR for ACTIVE SUBSCRIPTION lines at period end.
-- Naive answers include SERVICES lines and churned subscriptions.
CREATE OR REPLACE TABLE SUBSCRIPTIONS AS
SELECT SEQ4()+1 AS SUBSCRIPTION_ID,
       UNIFORM(13, 400, RANDOM(21)) AS ACCOUNT_ID,
       CASE WHEN UNIFORM(1, 100, RANDOM(22)) <= 78 THEN 'Subscription' ELSE 'Services' END AS PRODUCT_TYPE,
       UNIFORM(500, 25000, RANDOM(23)) AS MRR,
       DATEADD(day, UNIFORM(0, 600, RANDOM(24)), '2025-01-01'::DATE) AS START_DATE,
       CASE WHEN UNIFORM(1, 100, RANDOM(25)) <= 22 THEN DATEADD(day, UNIFORM(200, 900, RANDOM(26)), '2025-01-01'::DATE) END AS END_DATE
FROM TABLE(GENERATOR(ROWCOUNT => 1200));
ALTER TABLE SUBSCRIPTIONS ADD COLUMN STATUS STRING;
UPDATE SUBSCRIPTIONS SET STATUS = CASE WHEN END_DATE IS NOT NULL AND END_DATE <= '2026-11-17' THEN 'Churned' ELSE 'Active' END;

CREATE OR REPLACE TABLE INVOICES AS
