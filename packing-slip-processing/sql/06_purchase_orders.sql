USE SCHEMA PACKING_SLIP_PROCESSING.PACKING_SLIPS;

-- Create PURCHASE_ORDERS table
CREATE TABLE IF NOT EXISTS PURCHASE_ORDERS (
    PO_ID NUMBER AUTOINCREMENT START 1 INCREMENT 1 PRIMARY KEY,
    PO_NUMBER VARCHAR NOT NULL,
    SUPPLIER_NAME VARCHAR,
    ORDER_DATE DATE,
    EXPECTED_DELIVERY_DATE DATE,
    CREATED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

-- Create PO_LINE_ITEMS table
CREATE TABLE IF NOT EXISTS PO_LINE_ITEMS (
    PO_LINE_ID NUMBER AUTOINCREMENT START 1 INCREMENT 1 PRIMARY KEY,
    PO_ID NUMBER NOT NULL REFERENCES PURCHASE_ORDERS(PO_ID),
    LINE_NUMBER VARCHAR,
    PART_NUMBER VARCHAR,
    DESCRIPTION VARCHAR,
    QUANTITY_ORDERED NUMBER,
    UNIT_PRICE NUMBER(10,2),
    CREATED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

