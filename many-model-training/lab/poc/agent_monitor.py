def run_monitoring_cycle(session: Session = None, write_insights: bool = True,
                         use_agent: bool = False):
    """Full monitoring cycle: detect → analyze → synthesize → store.

    Steps:
    1. Compute fleet-wide health summary
    2. Detect drifting partitions (SQL-based, threshold from config)
    3. Analyze feature distributions for drifting partitions
    4. Detect prediction bias patterns (waste/lost-sales)
    5. Synthesize findings via Cortex Agent or AI_COMPLETE fallback
    6. Store insights to AGENT_INSIGHTS table

    Args:
        use_agent: If True, queries the Cortex Agent for synthesis.
                   If False, uses AI_COMPLETE directly with the structured analysis.
    """
    if session is None:
        session = create_session("agent_monitor")
        print(f"Connected: {session.get_current_account()}")

    print("=" * 60)
    print("ML MODEL MONITORING CYCLE")
    print("=" * 60)

    create_insights_table(session)
    insights_fqn = get_fully_qualified_name("AGENT_INSIGHTS")

    # Step 1: Fleet summary
    print("\n   [1/5] Computing fleet health summary...")
    fleet_summary = compute_fleet_summary(session)
    print(f"   Fleet: {fleet_summary.get('total_partitions', 0)} partitions, "
          f"{fleet_summary.get('drifting_partitions', 0)} drifting "
          f"({fleet_summary.get('drifting_pct', 0)}%)")
    print(f"   Avg MAPE: {fleet_summary.get('avg_fleet_mape', 0):.2%}, "
          f"Worst: {fleet_summary.get('worst_mape', 0):.2%}")

    # Step 2: Detect drift
    print("\n   [2/5] Detecting drifting partitions...")
    drifting = detect_drifting_partitions(session)

    if not drifting:
        print("   All models performing within threshold. No action needed.")
        return {"fleet_summary": fleet_summary, "insights": []}

    print(f"   Found {len(drifting)} partitions exceeding drift threshold")

    # Step 3: Feature distribution analysis
    print("\n   [3/5] Analyzing feature distributions...")
    drift_analyses = analyze_feature_distributions(session, drifting)
    shifted_count = sum(1 for a in drift_analyses if a["num_features_shifted"] > 0)
    print(f"   {shifted_count}/{len(drift_analyses)} partitions show feature distribution shifts")

    # Step 4: Bias detection
    print("\n   [4/5] Detecting prediction bias patterns...")
    bias = detect_prediction_bias(session)
    print(f"   Waste risk (over-prediction): {len(bias['waste_risk'])} partitions")
    print(f"   Lost sales risk (under-prediction): {len(bias['lost_sales_risk'])} partitions")

    # Step 5: Synthesis
    print("\n   [5/5] Generating monitoring report...")
    if use_agent:
        question = (
            f"We have {len(drifting)} drifting partitions with the worst MAPE at "
            f"{fleet_summary.get('worst_mape', 0):.1%}. "
            f"Feature analysis shows {shifted_count} partitions with distribution shifts. "
            f"What are the root causes and what should we do?"
        )
        report = query_monitoring_agent(session, question)
    else:
        report = synthesize_with_llm(session, drift_analyses, bias, fleet_summary)

    print(f"\n{'─' * 60}")
    print("MONITORING REPORT")
    print(f"{'─' * 60}")
    print(report)

    # Store insights
    if write_insights:
        for analysis in drift_analyses:
            partition_id = analysis["partition_id"]
            shifts_desc = "; ".join(
                s["description"] for s in analysis["feature_shifts"].values()
            ) if analysis["feature_shifts"] else "No clear feature shift detected"

            summary = f"Drift detected: MAPE {float(analysis['current_mape']):.1%} (threshold: {telemetry_cfg['drift_threshold_mape']:.0%})"
            detail = f"Partition {partition_id} exceeded drift threshold. Feature analysis: {shifts_desc}"
            recommendation = "Query the monitoring agent for detailed root cause analysis and recommended actions."

            session.sql(f"""
                INSERT INTO {insights_fqn}
                (INSIGHT_ID, CREATED_AT, CATEGORY, STORE_ITEM_ID, SUMMARY, DETAIL, RECOMMENDATION, STATUS, METADATA)
                SELECT UUID_STRING(), CURRENT_TIMESTAMP(), 'drift', '{partition_id}',
                       '{summary.replace("'", "''")}',
                       '{detail.replace("'", "''")}',
                       '{recommendation.replace("'", "''")}',
                       'new',
                       PARSE_JSON('{json.dumps(analysis["feature_shifts"], default=str).replace("'", "''")}')
            """).collect()

        for opp in bias["waste_risk"]:
            session.sql(f"""
                INSERT INTO {insights_fqn}
                (INSIGHT_ID, CREATED_AT, CATEGORY, STORE_ITEM_ID, SUMMARY, DETAIL, RECOMMENDATION, STATUS)
                SELECT UUID_STRING(), CURRENT_TIMESTAMP(), 'waste_reduction', '{opp["partition_id"]}',
                       'Over-predicting by {opp["avg_over_prediction"]:.1f} units/hr',
                       'Systematic over-prediction detected over {opp["observations"]} observations. Potential inventory waste.',
                       'Investigate demand patterns and consider retraining with recent data emphasis.',
                       'new'
            """).collect()

        for opp in bias["lost_sales_risk"]:
            session.sql(f"""
                INSERT INTO {insights_fqn}
                (INSIGHT_ID, CREATED_AT, CATEGORY, STORE_ITEM_ID, SUMMARY, DETAIL, RECOMMENDATION, STATUS)
                SELECT UUID_STRING(), CURRENT_TIMESTAMP(), 'lost_sales', '{opp["partition_id"]}',
                       'Under-predicting by {opp["avg_under_prediction"]:.1f} units/hr',
                       'Systematic under-prediction detected over {opp["observations"]} observations. Potential lost revenue.',
                       'Consider increasing forecast bias or retraining with recent demand uplift.',
                       'new'
            """).collect()

        total_insights = len(drift_analyses) + len(bias["waste_risk"]) + len(bias["lost_sales_risk"])
        print(f"\n   {total_insights} insights written to AGENT_INSIGHTS")

    return {
        "fleet_summary": fleet_summary,
        "drifting": drift_analyses,
        "bias": bias,
        "report": report,
    }


def get_recent_insights(session: Session, limit: int = 20) -> list:
    """Return recent insights for display."""
    insights_fqn = get_fully_qualified_name("AGENT_INSIGHTS")

    rows = session.sql(f"""
        SELECT * FROM {insights_fqn}
        ORDER BY CREATED_AT DESC
        LIMIT {limit}
    """).collect()

    return [dict(row) for row in rows]


