def synthesize_with_llm(session: Session, drift_analysis: list, bias_analysis: dict,
                        fleet_summary: dict) -> str:
    """Use AI_COMPLETE to synthesize statistical findings into a monitoring report.

    This is the fallback when the full Cortex Agent isn't set up yet.
    Passes structured analysis data to the LLM for natural-language synthesis.
    """
    analysis_payload = json.dumps({
        "fleet_summary": fleet_summary,
        "drifting_partitions": drift_analysis[:5],
        "prediction_bias": bias_analysis,
    }, indent=2, default=str)

    prompt = f"""You are an ML operations analyst for a retail demand forecasting system
with {fleet_summary.get('total_partitions', 0)} partition-level models.

Here is the latest monitoring analysis:

{analysis_payload}

Provide a structured monitoring report with:
1. FLEET HEALTH: One-paragraph summary of overall fleet health
2. TOP DRIFT ISSUES: For each drifting partition, explain the likely cause based on feature shifts
3. BIAS PATTERNS: Summarize any systematic over/under-prediction and business impact
4. RECOMMENDED ACTIONS: Prioritized list of 3-5 specific actions (retrain X, investigate Y, add feature Z)

Be specific — cite partition IDs, MAPE values, and feature shift magnitudes."""

    try:
        result = session.sql(f"""
            SELECT AI_COMPLETE('mistral-large2', $${prompt}$$) AS RESPONSE
        """).collect()
        return result[0]["RESPONSE"]
    except Exception as e:
        return f"AI_COMPLETE unavailable ({e}). Raw analysis:\n{analysis_payload}"


