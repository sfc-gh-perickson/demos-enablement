"""ML Model Monitoring via Cortex Agent.

This module provides a complete monitoring system for Many-Model Training deployments:

1. Statistical drift detection (SQL-based, no LLM needed)
2. Feature distribution analysis (compares recent vs historical)
3. Prediction bias detection (waste/lost-sales opportunities)
4. Cortex Agent creation (with Analyst + Search tools for interactive monitoring)
5. Agent-powered synthesis (queries the agent for root cause analysis)

The Cortex Agent is configured with:
- cortex_analyst_text_to_sql: queries telemetry, model catalog, and experiment data
- cortex_search: retrieves past insights and recommendations for context
"""
