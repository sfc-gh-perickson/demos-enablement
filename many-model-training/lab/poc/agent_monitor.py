def detect_drifting_partitions(session: Session) -> list:
    """Identify partitions where rolling MAPE exceeds threshold."""
    telemetry_fqn = get_fully_qualified_name("FORECAST_TELEMETRY")

    drifting = session.sql(f"""
        SELECT {GRAIN},
               MAX(ROLLING_7D_MAPE) AS CURRENT_MAPE,
               COUNT(*) AS OBSERVATION_COUNT,
               AVG(ABS(ERROR)) AS AVG_ABS_ERROR,
               STDDEV(ERROR) AS ERROR_VOLATILITY
        FROM {telemetry_fqn}
        WHERE DRIFT_FLAG = TRUE
        GROUP BY {GRAIN}
        ORDER BY CURRENT_MAPE DESC
        LIMIT {telemetry_cfg.get('alert_top_n', 20)}
    """).collect()

    return [dict(row) for row in drifting]


def analyze_feature_distributions(session: Session, drifting_partitions: list) -> list:
    """Compare recent vs historical feature distributions for drifting partitions.

    For each drifting partition, computes:
    - Mean shift per feature (recent 7 days vs prior history)
    - Identifies which features shifted most significantly
    """
    feature_fqn = get_fully_qualified_name("FEATURE_TABLE")

    analyses = []
    for partition in drifting_partitions[:10]:
        partition_id = partition[GRAIN]
        try:
            # Recent 7 days vs all prior data
            comparison = session.sql(f"""
                WITH recent AS (
                    SELECT
                        AVG(WEATHER_TEMP) AS AVG_TEMP,
                        AVG(CASE WHEN IS_HOLIDAY THEN 1 ELSE 0 END) AS HOLIDAY_RATE,
                        AVG(CASE WHEN IS_WEEKEND THEN 1 ELSE 0 END) AS WEEKEND_RATE,
                        AVG(CASE WHEN EVENT_FLAG THEN 1 ELSE 0 END) AS EVENT_RATE,
                        AVG(ROLLING_7D_AVG) AS AVG_ROLLING_7D,
                        AVG(DEMAND) AS AVG_DEMAND
                    FROM {feature_fqn}
                    WHERE {GRAIN} = '{partition_id}'
                      AND {TIME} >= DATEADD(day, -7, (SELECT MAX({TIME}) FROM {feature_fqn}))
                ),
                historical AS (
                    SELECT
                        AVG(WEATHER_TEMP) AS AVG_TEMP,
                        AVG(CASE WHEN IS_HOLIDAY THEN 1 ELSE 0 END) AS HOLIDAY_RATE,
                        AVG(CASE WHEN IS_WEEKEND THEN 1 ELSE 0 END) AS WEEKEND_RATE,
                        AVG(CASE WHEN EVENT_FLAG THEN 1 ELSE 0 END) AS EVENT_RATE,
                        AVG(ROLLING_7D_AVG) AS AVG_ROLLING_7D,
                        AVG(DEMAND) AS AVG_DEMAND
                    FROM {feature_fqn}
                    WHERE {GRAIN} = '{partition_id}'
                      AND {TIME} < DATEADD(day, -7, (SELECT MAX({TIME}) FROM {feature_fqn}))
                )
                SELECT
                    r.AVG_TEMP AS RECENT_TEMP, h.AVG_TEMP AS HIST_TEMP,
                    r.HOLIDAY_RATE AS RECENT_HOLIDAY, h.HOLIDAY_RATE AS HIST_HOLIDAY,
                    r.WEEKEND_RATE AS RECENT_WEEKEND, h.WEEKEND_RATE AS HIST_WEEKEND,
                    r.EVENT_RATE AS RECENT_EVENT, h.EVENT_RATE AS HIST_EVENT,
                    r.AVG_ROLLING_7D AS RECENT_ROLLING, h.AVG_ROLLING_7D AS HIST_ROLLING,
                    r.AVG_DEMAND AS RECENT_DEMAND, h.AVG_DEMAND AS HIST_DEMAND
                FROM recent r, historical h
            """).collect()

            feature_shifts = {}
            if comparison:
                row = comparison[0]
                # Temperature shift
                if row["RECENT_TEMP"] is not None and row["HIST_TEMP"] is not None:
                    temp_diff = abs(float(row["RECENT_TEMP"]) - float(row["HIST_TEMP"]))
                    if temp_diff > 15:
                        feature_shifts["WEATHER_TEMP"] = {
                            "recent": round(float(row["RECENT_TEMP"]), 1),
                            "historical": round(float(row["HIST_TEMP"]), 1),
                            "shift": round(temp_diff, 1),
                            "description": f"Temperature shifted from {float(row['HIST_TEMP']):.0f}F to {float(row['RECENT_TEMP']):.0f}F"
                        }
                # Event rate shift
                if row["RECENT_EVENT"] is not None and row["HIST_EVENT"] is not None:
                    event_diff = float(row["RECENT_EVENT"]) - float(row["HIST_EVENT"])
                    if abs(event_diff) > 0.1:
                        feature_shifts["EVENT_FLAG"] = {
                            "recent": round(float(row["RECENT_EVENT"]), 3),
                            "historical": round(float(row["HIST_EVENT"]), 3),
                            "shift": round(event_diff, 3),
                            "description": f"Event rate {'increased' if event_diff > 0 else 'decreased'} from {float(row['HIST_EVENT']):.1%} to {float(row['RECENT_EVENT']):.1%}"
                        }
                # Demand level shift (target drift)
                if row["RECENT_DEMAND"] is not None and row["HIST_DEMAND"] is not None:
                    demand_pct_change = (float(row["RECENT_DEMAND"]) - float(row["HIST_DEMAND"])) / max(float(row["HIST_DEMAND"]), 1)
                    if abs(demand_pct_change) > 0.2:
                        feature_shifts["DEMAND_LEVEL"] = {
                            "recent": round(float(row["RECENT_DEMAND"]), 1),
                            "historical": round(float(row["HIST_DEMAND"]), 1),
                            "shift_pct": round(demand_pct_change * 100, 1),
                            "description": f"Demand level shifted {demand_pct_change*100:.0f}% (from {float(row['HIST_DEMAND']):.1f} to {float(row['RECENT_DEMAND']):.1f} units/hr)"
                        }
        except Exception:
            feature_shifts = {}

        analyses.append({
            "partition_id": partition_id,
            "current_mape": partition.get("CURRENT_MAPE"),
            "feature_shifts": feature_shifts,
            "num_features_shifted": len(feature_shifts),
        })

    return analyses


def detect_prediction_bias(session: Session) -> dict:
    """Detect systematic over/under-prediction patterns across partitions."""
    telemetry_fqn = get_fully_qualified_name("FORECAST_TELEMETRY")

    # Over-predicting partitions (waste)
    over_pred = session.sql(f"""
        SELECT {GRAIN}, AVG(ERROR) AS AVG_BIAS, COUNT(*) AS N,
               STDDEV(ERROR) AS BIAS_VOLATILITY
        FROM {telemetry_fqn}
        WHERE ERROR > 0
        GROUP BY {GRAIN}
        HAVING AVG(ERROR) > 3 AND COUNT(*) > 100
        ORDER BY AVG_BIAS DESC
        LIMIT 5
    """).collect()

    # Under-predicting partitions (lost sales)
    under_pred = session.sql(f"""
        SELECT {GRAIN}, AVG(ERROR) AS AVG_BIAS, COUNT(*) AS N,
               STDDEV(ERROR) AS BIAS_VOLATILITY
        FROM {telemetry_fqn}
        WHERE ERROR < 0
        GROUP BY {GRAIN}
        HAVING AVG(ERROR) < -3 AND COUNT(*) > 100
        ORDER BY AVG_BIAS ASC
        LIMIT 5
    """).collect()

    return {
        "waste_risk": [
            {
                "partition_id": row[GRAIN],
                "avg_over_prediction": round(float(row["AVG_BIAS"]), 1),
                "observations": int(row["N"]),
            }
            for row in over_pred
        ],
        "lost_sales_risk": [
            {
                "partition_id": row[GRAIN],
                "avg_under_prediction": round(abs(float(row["AVG_BIAS"])), 1),
                "observations": int(row["N"]),
            }
            for row in under_pred
        ],
    }


def compute_fleet_summary(session: Session) -> dict:
    """Compute fleet-wide health summary statistics."""
    telemetry_fqn = get_fully_qualified_name("FORECAST_TELEMETRY")

    summary = session.sql(f"""
        SELECT
            COUNT(DISTINCT {GRAIN}) AS TOTAL_PARTITIONS,
            COUNT(DISTINCT CASE WHEN DRIFT_FLAG = TRUE THEN {GRAIN} END) AS DRIFTING_PARTITIONS,
            AVG(ROLLING_7D_MAPE) AS AVG_FLEET_MAPE,
            MEDIAN(ROLLING_7D_MAPE) AS MEDIAN_FLEET_MAPE,
            MAX(ROLLING_7D_MAPE) AS WORST_MAPE,
            AVG(ABS(ERROR)) AS AVG_ABS_ERROR
        FROM {telemetry_fqn}
        WHERE ROLLING_7D_MAPE IS NOT NULL
    """).collect()

    if summary:
        row = summary[0]
        return {
            "total_partitions": int(row["TOTAL_PARTITIONS"] or 0),
            "drifting_partitions": int(row["DRIFTING_PARTITIONS"] or 0),
            "drifting_pct": round(int(row["DRIFTING_PARTITIONS"] or 0) / max(int(row["TOTAL_PARTITIONS"] or 1), 1) * 100, 1),
            "avg_fleet_mape": round(float(row["AVG_FLEET_MAPE"] or 0), 4),
            "median_fleet_mape": round(float(row["MEDIAN_FLEET_MAPE"] or 0), 4),
            "worst_mape": round(float(row["WORST_MAPE"] or 0), 4),
            "avg_abs_error": round(float(row["AVG_ABS_ERROR"] or 0), 2),
        }
    return {}


